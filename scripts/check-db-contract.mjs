// Checks that the app and the SQL in the repo agree, so a missing or renamed database
// function is caught at build time instead of by users.
//   node scripts/check-db-contract.mjs        check (runs before every build)
//   node scripts/check-db-contract.mjs --sql  write supabase/verify_database.sql, which lists
//                                             what a live database is missing when run in the SQL Editor
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const read = (p) => readFileSync(join(root, p), "utf8");
const walk = (dir) => readdirSync(join(root, dir)).flatMap((f) => {
  const p = join(dir, f);
  return statSync(join(root, p)).isDirectory() ? walk(p) : /\.(tsx?|mjs)$/.test(f) ? [p] : [];
});

// 1. Every rpc("name", { p_x: ... }) the app and edge functions make.
const calls = new Map();
for (const f of [...walk("src"), ...walk("supabase/functions")]) {
  const src = read(f);
  for (const m of src.matchAll(/\.rpc\(\s*["'`]([a-z0-9_]+)["'`]\s*(?:,\s*\{([^}]*)\})?/g)) {
    const params = [...(m[2] || "").matchAll(/\b(p_[a-z0-9_]+)\s*:/g)].map((x) => x[1]);
    const c = calls.get(m[1]) || { files: new Set(), params: new Set() };
    c.files.add(f); params.forEach((p) => c.params.add(p));
    calls.set(m[1], c);
  }
}

// 2. Function definitions in the full setup file (the latest definition wins).
const setup = read("supabase/setup_all_in_one.sql");
const defs = new Map();
for (const m of setup.matchAll(/create\s+(?:or\s+replace\s+)?function\s+(?:public\.)?([a-z0-9_]+)\s*\(([^)]*)\)/gi)) {
  const args = [...m[2].matchAll(/\b(p_[a-z0-9_]+)\b/g)].map((x) => x[1]);
  const list = defs.get(m[1]) || [];
  list.push(new Set(args));
  defs.set(m[1], list);
}

const errors = [];
for (const [name, c] of calls) {
  const overloads = defs.get(name);
  if (!overloads) { errors.push(`rpc ${name}() is called in ${[...c.files].join(", ")} but no SQL defines it`); continue; }
  if (!overloads.some((args) => [...c.params].every((p) => args.has(p))))
    errors.push(`rpc ${name}() is called with ${[...c.params].join(", ")} but no SQL definition takes all of them`);
}

// 3. Migrations: unique numbers, and every one is in both bundles.
const migs = readdirSync(join(root, "supabase/migrations")).filter((f) => f.endsWith(".sql")).sort();
const seen = new Map();
for (const f of migs) {
  const n = f.split("_")[0];
  if (seen.has(n)) errors.push(`two migrations share number ${n}: ${seen.get(n)} and ${f}`);
  seen.set(n, f);
}
const update = read("supabase/update_existing_database.sql");
for (const f of migs) {
  const body = read(`supabase/migrations/${f}`).trim();
  const probe = body.split("\n").find((l) => /^(create|alter|drop|insert)\b/i.test(l.trim())) || body.slice(0, 120);
  if (!setup.includes(probe)) errors.push(`${f} is not in setup_all_in_one.sql`);
  // The update file starts after the base schema (migrations 1-5).
  if (Number(f.slice(8, 14)) > 5 && !update.includes(probe)) errors.push(`${f} is not in update_existing_database.sql`);
}

if (process.argv.includes("--sql")) {
  const rows = [...calls].sort().map(([n, c]) => `  ('${n}', array[${[...c.params].sort().map((p) => `'${p}'`).join(", ")}]::text[])`);
  writeFileSync(join(root, "supabase/verify_database.sql"), `-- Generated by scripts/check-db-contract.mjs. Run in the Supabase SQL Editor.
-- No rows = the database has every function the app calls, with the arguments it uses.
-- Any row = run the run-now SQL bundles (or update_existing_database.sql) before using the app.
with needed(fn, params) as (values
${rows.join(",\n")}
)
select n.fn as missing_function, n.params as with_arguments
from needed n
where not exists (
  select 1 from pg_proc p join pg_namespace s on s.oid = p.pronamespace
  where s.nspname = 'public' and p.proname = n.fn
    and n.params <@ coalesce(p.proargnames, '{}'::text[])
)
order by 1;
`);
  console.log("wrote supabase/verify_database.sql");
}

if (errors.length) {
  console.error("Database contract check failed:\n- " + errors.join("\n- "));
  process.exit(1);
}
console.log(`Database contract OK: ${calls.size} functions, ${migs.length} migrations`);
