#!/usr/bin/env node
// General AI Restaurant Onboarding Agent CLI
// Usage:
//   node scripts/onboard/index.mjs --city Varanasi
//   node scripts/onboard/index.mjs --city Varanasi --area Godowlia --limit 5
//   node scripts/onboard/index.mjs --city Varanasi --dry-run
//   node scripts/onboard/index.mjs --city Varanasi --sql

import { discoverPlaces } from "./places-service.mjs";
import { extractOrGenerateMenu } from "./menu-ai.mjs";
import { getBootstrappedReviews } from "./review-generator.mjs";
import { onboardRestaurant } from "./db-provisioner.mjs";
import { scrapeRestaurantWebsite } from "./website-scraper.mjs";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../..", import.meta.url));

function parseArgs() {
  const args = process.argv.slice(2);
  const options = {
    city: "Varanasi",
    area: null,
    limit: 10,
    dryRun: false,
    sql: false
  };

  for (let i = 0; i < args.length; i++) {
    const arg = args[i];
    if (arg === "--city" && args[i + 1]) {
      options.city = args[++i];
    } else if (arg === "--area" && args[i + 1]) {
      options.area = args[++i];
    } else if (arg === "--limit" && args[i + 1]) {
      options.limit = parseInt(args[++i], 10) || 10;
    } else if (arg === "--dry-run") {
      options.dryRun = true;
    } else if (arg === "--sql") {
      options.sql = true;
    } else if (arg === "--help" || arg === "-h") {
      console.log(`
🤖 AI Restaurant Onboarding Agent CLI

Usage:
  node scripts/onboard/index.mjs [options]

Options:
  --city <name>     Target city (default: "Varanasi")
  --area <name>     Target area/neighborhood (e.g. "Godowlia", "Assi Ghat")
  --limit <n>       Maximum number of places to onboard (default: 10)
  --dry-run         Simulate discovery and synthesis without writing to DB
  --sql             Generate SQL migration file without running DB writes
  --help, -h        Show this help message
`);
      process.exit(0);
    }
  }
  return options;
}

function escapeSql(str) {
  if (str === null || str === undefined) return "NULL";
  return `'${String(str).replace(/'/g, "''")}'`;
}

function generateSqlMigration(placesWithData) {
  const statements = [
    `-- Automated Migration generated by AI Restaurant Onboarding Agent`,
    `-- Generated on: ${new Date().toISOString()}`,
    `BEGIN;`,
    ``
  ];

  for (const { place, menuItems, reviews } of placesWithData) {
    const placeVar = `place_${place.name.toLowerCase().replace(/[^a-z0-9]/g, "_").slice(0, 20)}`;
    const hoursJson = JSON.stringify(place.hours || {}).replace(/'/g, "''");
    const linksJson = JSON.stringify(place.links || {}).replace(/'/g, "''");

    statements.push(`-- Place: ${place.name}`);
    statements.push(`DO $$`);
    statements.push(`DECLARE`);
    statements.push(`  v_place_id uuid;`);
    statements.push(`  v_item_id uuid;`);
    statements.push(`BEGIN`);
    statements.push(`  -- 1. Insert or update Place`);
    statements.push(`  INSERT INTO public.places (name, category, area, city, about, price_level, location, hours, kind, cover_path, logo_path, links, status, google_place_id)`);
    statements.push(`  VALUES (`);
    statements.push(`    ${escapeSql(place.name)}, ${escapeSql(place.category)}, ${escapeSql(place.area)}, ${escapeSql(place.city)},`);
    statements.push(`    ${escapeSql(place.about)}, ${place.price_level || 1}, ST_SetSRID(ST_MakePoint(${place.lng}, ${place.lat}), 4326),`);
    statements.push(`    '${hoursJson}'::jsonb, 'food', ${escapeSql(place.cover_path)}, ${escapeSql(place.logo_path)},`);
    statements.push(`    '${linksJson}'::jsonb, 'live', ${escapeSql(place.google_place_id)}`);
    statements.push(`  )`);
    statements.push(`  ON CONFLICT (name, city) DO UPDATE SET`);
    statements.push(`    category = EXCLUDED.category, area = EXCLUDED.area, about = EXCLUDED.about, location = EXCLUDED.location`);
    statements.push(`  RETURNING id INTO v_place_id;`);
    statements.push(``);

    statements.push(`  -- 2. Insert Menu Items`);
    for (const item of menuItems) {
      const dietArr = `ARRAY[${item.diet.map((d) => `'${d}'`).join(",")}]::text[]`;
      statements.push(`  INSERT INTO public.items (place_id, name, price_inr, description, section, diet, is_listed, sort_order, image_path)`);
      statements.push(`  VALUES (v_place_id, ${escapeSql(item.name)}, ${item.price_inr}, ${escapeSql(item.description)}, ${escapeSql(item.section)}, ${dietArr}, ${item.is_listed ? "true" : "false"}, ${item.sort_order || 0}, ${escapeSql(item.image_path)})`);
      statements.push(`  ON CONFLICT (place_id, name_normalized) DO NOTHING;`);
    }
    statements.push(``);

    statements.push(`  -- 3. Provision Active QR Code`);
    const slug = place.name.toLowerCase().replace(/[^a-z0-9]+/g, "-").slice(0, 10);
    const token = `vns-${slug}-${crypto.randomUUID().slice(0, 8)}`;
    statements.push(`  INSERT INTO public.qr_codes (place_id, token, table_label, active, seats, jar_size, refill_seconds)`);
    statements.push(`  VALUES (v_place_id, '${token}', 'Table 1 / Counter', true, 4, 20, 30)`);
    statements.push(`  ON CONFLICT DO NOTHING;`);
    statements.push(``);

    statements.push(`  -- 4. Provision Subscription`);
    statements.push(`  INSERT INTO public.subscriptions (place_id, plan, status, trial_reviews_left, period_end, billing_interval, cancel_at_period_end)`);
    statements.push(`  VALUES (v_place_id, 'starter', 'active', 100, NOW() + INTERVAL '1 year', 'year', false)`);
    statements.push(`  ON CONFLICT (place_id) DO UPDATE SET status = 'active';`);
    statements.push(``);

    statements.push(`END $$;`);
    statements.push(``);
  }

  statements.push(`COMMIT;`);
  return statements.join("\n");
}

async function main() {
  const options = parseArgs();
  console.log(`\n======================================================`);
  console.log(`🤖 AI RESTAURANT ONBOARDING AGENT`);
  console.log(`Target: ${options.city}${options.area ? ` | Area: ${options.area}` : ""} | Limit: ${options.limit}`);
  console.log(`Mode:   ${options.dryRun ? "DRY-RUN (Simulation)" : options.sql ? "SQL GENERATION" : "LIVE SUPABASE INGESTION"}`);
  console.log(`======================================================\n`);

  // Step 1: Discover Businesses
  const places = await discoverPlaces({
    city: options.city,
    area: options.area,
    limit: options.limit
  });

  console.log(`Discovered ${places.length} business entities.\n`);

  const placesWithData = [];

  for (let i = 0; i < places.length; i++) {
    const place = places[i];
    console.log(`[${i + 1}/${places.length}] Analyzing "${place.name}"...`);

    // Step 2: Extract & Enrich Menu
    const menuItems = await extractOrGenerateMenu(place.name, place.category);

    // Step 2b: Real Website Deep Scraping (Services, Amenities, Contacts, Live Menu)
    const websiteUrl = place.links.find((l) => l.kind === "website")?.url;
    if (websiteUrl) {
      console.log(`  🌐 Scraping official website: ${websiteUrl}...`);
      const webData = await scrapeRestaurantWebsite(websiteUrl);
      if (webData) {
        if (webData.amenities && webData.amenities.length > 0) {
          console.log(`    -> Real amenities verified: ${webData.amenities.join(", ")}`);
          place.about = `${place.about}\n\nServices & Amenities: ${webData.amenities.join(" • ")}`;
        }
        if (webData.phones && webData.phones.length > 0 && !place.phone) {
          place.phone = webData.phones[0];
        }
        if (webData.socialLinks && webData.socialLinks.length > 0) {
          for (const sl of webData.socialLinks) {
            if (!place.links.some((l) => l.kind === sl.kind)) {
              place.links.push(sl);
            }
          }
        }
        if (webData.extractedDishes && webData.extractedDishes.length > 0) {
          console.log(`    -> Extracted ${webData.extractedDishes.length} live dishes from official website`);
          for (const d of webData.extractedDishes) {
            if (!menuItems.some((it) => it.name.toLowerCase() === d.name.toLowerCase())) {
              menuItems.push(d);
            }
          }
        }
      }
    }
    console.log(`  🍽️  Menu: ${menuItems.length} dishes ready.`);

    // Step 3: Google Reviews Bootstrapping
    const reviews = getBootstrappedReviews(place.name, menuItems);
    console.log(`  ⭐  Google reputation: ${reviews.length} reviews matched.`);

    placesWithData.push({ place, menuItems, reviews });
  }

  // Handle SQL Mode
  if (options.sql) {
    const sqlContent = generateSqlMigration(placesWithData);
    const sqlPath = join(root, `scripts/onboard/onboard-${options.city.toLowerCase()}.sql`);
    writeFileSync(sqlPath, sqlContent, "utf8");
    console.log(`\n💾 SQL migration written to: ${sqlPath}`);
    return;
  }

  // Handle Dry-Run Mode
  if (options.dryRun) {
    console.log(`\n✨ [DRY RUN COMPLETE] Simulated onboarding for ${placesWithData.length} places.`);
    console.table(
      placesWithData.map(({ place, menuItems, reviews }) => ({
        Name: place.name,
        Area: place.area,
        Rating: place.google_rating,
        Dishes: menuItems.length,
        TopPicks: menuItems.filter((m) => m.is_listed).map((m) => m.name).join(", "),
        Reviews: reviews.length
      }))
    );
    return;
  }

  // Handle Live Ingestion Mode
  console.log(`\n🚀 Ingesting places into live database...`);
  const results = [];
  for (const { place, menuItems, reviews } of placesWithData) {
    try {
      const summary = await onboardRestaurant(place, menuItems, reviews);
      results.push({ success: true, ...summary });
    } catch (err) {
      console.error(`❌ Ingestion failed for ${place.name}:`, err.message);
      results.push({ success: false, name: place.name, error: err.message });
    }
  }

  console.log(`\n✅ Ingestion finished. Summary:`);
  console.table(
    results.map((r) => ({
      Name: r.name,
      Status: r.success ? "✅ Onboarded" : "❌ Error",
      Area: r.area || "—",
      Dishes: r.itemsCount || 0,
      Reviews: r.reviewsCount || 0,
      QR_Token: r.qrToken || "—",
      Place_URL: r.placeUrl || "—"
    }))
  );
}

main().catch((err) => {
  console.error("CLI Agent Error:", err);
  process.exit(1);
});
